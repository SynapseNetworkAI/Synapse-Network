from collections.abc import Sequence
from datetime import datetime
from decimal import Decimal
from typing import Protocol

from src.domain import (
    AdminActionAudit,
    AdminApproval,
    AdminApprovalEvent,
    AdminApprovalStep,
    AdminAuditExport,
    AdminExecutionAttempt,
    AdminExecutionJob,
    AdminMfaEnrollmentChallenge,
    AdminMfaFactor,
    AdminMenuConfigSnapshot,
    AdminInAppNotification,
    AdminPermission,
    AdminRole,
    AdminRolePermission,
    AdminSession,
    AdminUser,
    AdminUserRoleBinding,
)


class AdminIdentityRepository(Protocol):
    def get_user_by_id(self, admin_id: str) -> AdminUser | None: ...
    def get_user_by_email(self, email: str) -> AdminUser | None: ...
    def list_users(self, status: str | None = None, limit: int = 100) -> Sequence[AdminUser]: ...
    def create_user(self, user: AdminUser) -> AdminUser: ...
    def update_user(self, user: AdminUser) -> AdminUser: ...
    def update_password_hash(self, admin_id: str, password_hash: str) -> None: ...
    def list_mfa_factors(self, admin_id: str) -> Sequence[AdminMfaFactor]: ...
    def get_mfa_factor_by_id(self, factor_id: str) -> AdminMfaFactor | None: ...
    def get_mfa_factor_by_identity(self, admin_id: str, factor_type: str, factor_label: str) -> AdminMfaFactor | None: ...
    def upsert_mfa_factor(self, factor: AdminMfaFactor) -> AdminMfaFactor: ...
    def list_mfa_enrollment_challenges(self, admin_id: str) -> Sequence[AdminMfaEnrollmentChallenge]: ...
    def get_mfa_enrollment_challenge_by_token_hash(self, token_hash: str) -> AdminMfaEnrollmentChallenge | None: ...
    def upsert_mfa_enrollment_challenge(self, challenge: AdminMfaEnrollmentChallenge) -> AdminMfaEnrollmentChallenge: ...
    def get_session_by_id(self, session_id: str) -> AdminSession | None: ...
    def create_session(self, session: AdminSession) -> AdminSession: ...
    def revoke_session(self, session_id: str) -> None: ...
    def touch_last_login(self, admin_id: str) -> None: ...
    def record_login_failure(self, admin_id: str, failed_at: datetime) -> AdminUser | None: ...
    def clear_login_failures(self, admin_id: str) -> AdminUser | None: ...
    def lock_user_until(self, admin_id: str, locked_until: datetime) -> AdminUser | None: ...


class AdminAuthorizationRepository(Protocol):
    def list_roles(self) -> Sequence[AdminRole]: ...
    def get_role(self, role_key: str) -> AdminRole | None: ...
    def create_role(self, role: AdminRole) -> AdminRole: ...
    def update_role(self, role: AdminRole) -> AdminRole: ...
    def list_permissions(self) -> Sequence[AdminPermission]: ...
    def list_role_permissions(self, role_key: str) -> Sequence[AdminRolePermission]: ...
    def replace_role_permissions(self, role_key: str, permissions: Sequence[AdminRolePermission]) -> Sequence[AdminRolePermission]: ...
    def list_role_bindings(self, admin_id: str) -> Sequence[AdminUserRoleBinding]: ...
    def create_role_binding(self, binding: AdminUserRoleBinding) -> AdminUserRoleBinding: ...
    def replace_role_bindings(
        self,
        admin_id: str,
        bindings: Sequence[AdminUserRoleBinding],
    ) -> Sequence[AdminUserRoleBinding]: ...


class AdminApprovalRepository(Protocol):
    def list_approvals(
        self,
        status: str | None = None,
        approval_type: str | None = None,
        limit: int = 20,
    ) -> Sequence[AdminApproval]: ...
    def count_pending_approvals(self) -> int: ...
    def count_approvals(
        self,
        statuses: Sequence[str] | None = None,
        approval_type: str | None = None,
    ) -> int: ...
    def sum_approval_amount(
        self,
        statuses: Sequence[str] | None = None,
        approval_type: str | None = None,
    ) -> Decimal: ...
    def get_approval(self, approval_id: str) -> AdminApproval | None: ...
    def list_approval_steps(self, approval_id: str) -> Sequence[AdminApprovalStep]: ...
    def create_approval(self, approval: AdminApproval) -> AdminApproval: ...
    def update_approval(self, approval: AdminApproval) -> AdminApproval: ...
    def upsert_approval_step(self, step: AdminApprovalStep) -> AdminApprovalStep: ...
    def append_approval_event(self, event: AdminApprovalEvent) -> AdminApprovalEvent: ...
    def list_execution_jobs(
        self,
        status: str | None = None,
        target_system: str | None = None,
        approval_id: str | None = None,
        limit: int = 20,
    ) -> Sequence[AdminExecutionJob]: ...
    def get_execution_job(self, job_id: str) -> AdminExecutionJob | None: ...
    def enqueue_execution_job(self, job: AdminExecutionJob) -> AdminExecutionJob: ...
    def claim_execution_job(
        self,
        job_id: str,
        from_statuses: Sequence[str],
        claimed_job: AdminExecutionJob,
    ) -> AdminExecutionJob | None: ...
    def update_execution_job(self, job: AdminExecutionJob) -> AdminExecutionJob: ...
    def list_execution_attempts(self, job_id: str) -> Sequence[AdminExecutionAttempt]: ...
    def append_execution_attempt(self, attempt: AdminExecutionAttempt) -> AdminExecutionAttempt: ...
    def update_execution_attempt(self, attempt: AdminExecutionAttempt) -> AdminExecutionAttempt: ...
    def latest_activity_at(self) -> datetime | None: ...


class AdminAuditRepository(Protocol):
    def append_action(self, audit: AdminActionAudit) -> AdminActionAudit: ...
    def list_actions(
        self,
        action_type: str | None = None,
        result_status: str | None = None,
        operator_id: str | None = None,
        approval_id: str | None = None,
        job_id: str | None = None,
        limit: int = 50,
    ) -> Sequence[AdminActionAudit]: ...
    def count_alerts(self) -> int: ...
    def latest_activity_at(self) -> datetime | None: ...
    def record_export(self, audit_export: AdminAuditExport) -> AdminAuditExport: ...


class AdminConfigRepository(Protocol):
    def get_menu_config(self, config_key: str) -> AdminMenuConfigSnapshot | None: ...
    def save_menu_config(self, snapshot: AdminMenuConfigSnapshot) -> AdminMenuConfigSnapshot: ...


class AdminNotificationRepository(Protocol):
    def enqueue(self, notification: AdminInAppNotification) -> AdminInAppNotification: ...
    def list_for_admin(
        self,
        *,
        admin_id: str,
        limit: int = 20,
        unread_only: bool = False,
    ) -> Sequence[AdminInAppNotification]: ...
    def unread_count_for_admin(self, *, admin_id: str) -> int: ...
    def mark_read(self, *, admin_id: str, notification_id: str) -> bool: ...
    def mark_all_read(self, *, admin_id: str) -> int: ...
    def archive(self, *, admin_id: str, notification_id: str) -> bool: ...


class AdminStore(Protocol):
    @property
    def identity(self) -> AdminIdentityRepository: ...

    @property
    def authorization(self) -> AdminAuthorizationRepository: ...

    @property
    def approval(self) -> AdminApprovalRepository: ...

    @property
    def audit(self) -> AdminAuditRepository: ...

    @property
    def config(self) -> AdminConfigRepository: ...

    @property
    def notifications(self) -> AdminNotificationRepository: ...
