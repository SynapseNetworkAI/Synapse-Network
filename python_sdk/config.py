def load_contract_config():
    """
    Loads the contract addresses from the frontend's contract-config.json
    generated by Hardhat deployment scripts.
    """
    config_path = os.path.join(os.path.dirname(__file__), '..', 'frontend', 'src', 'contract-config.json')
    if not os.path.exists(config_path):
        raise Exception(f"Config not found at {config_path}")
    with open(config_path, 'r') as f:
        return json.load(f)
