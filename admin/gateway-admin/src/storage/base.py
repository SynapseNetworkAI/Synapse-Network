from collections.abc import Sequence
from typing import Protocol

from src.domain import (
    AdminActionAudit,
    AdminApproval,
    AdminApprovalEvent,
    AdminApprovalStep,
    AdminAuditExport,
    AdminExecutionAttempt,
    AdminExecutionJob,
    AdminMfaFactor,
    AdminPermission,
    AdminRole,
    AdminRolePermission,
    AdminSession,
    AdminUser,
    AdminUserRoleBinding,
)


class AdminIdentityRepository(Protocol):
    def get_user_by_id(self, admin_id: str) -> AdminUser | None: ...
    def get_user_by_email(self, email: str) -> AdminUser | None: ...
    def list_mfa_factors(self, admin_id: str) -> Sequence[AdminMfaFactor]: ...
    def get_session_by_id(self, session_id: str) -> AdminSession | None: ...
    def create_session(self, session: AdminSession) -> AdminSession: ...
    def revoke_session(self, session_id: str) -> None: ...
    def touch_last_login(self, admin_id: str) -> None: ...


class AdminAuthorizationRepository(Protocol):
    def list_roles(self) -> Sequence[AdminRole]: ...
    def list_permissions(self) -> Sequence[AdminPermission]: ...
    def list_role_permissions(self, role_key: str) -> Sequence[AdminRolePermission]: ...
    def list_role_bindings(self, admin_id: str) -> Sequence[AdminUserRoleBinding]: ...


class AdminApprovalRepository(Protocol):
    def list_approvals(
        self,
        status: str | None = None,
        approval_type: str | None = None,
        limit: int = 20,
    ) -> Sequence[AdminApproval]: ...
    def count_pending_approvals(self) -> int: ...
    def get_approval(self, approval_id: str) -> AdminApproval | None: ...
    def list_approval_steps(self, approval_id: str) -> Sequence[AdminApprovalStep]: ...
    def create_approval(self, approval: AdminApproval) -> AdminApproval: ...
    def update_approval(self, approval: AdminApproval) -> AdminApproval: ...
    def upsert_approval_step(self, step: AdminApprovalStep) -> AdminApprovalStep: ...
    def append_approval_event(self, event: AdminApprovalEvent) -> AdminApprovalEvent: ...
    def enqueue_execution_job(self, job: AdminExecutionJob) -> AdminExecutionJob: ...
    def append_execution_attempt(self, attempt: AdminExecutionAttempt) -> AdminExecutionAttempt: ...


class AdminAuditRepository(Protocol):
    def append_action(self, audit: AdminActionAudit) -> AdminActionAudit: ...
    def record_export(self, audit_export: AdminAuditExport) -> AdminAuditExport: ...


class AdminStore(Protocol):
    @property
    def identity(self) -> AdminIdentityRepository: ...

    @property
    def authorization(self) -> AdminAuthorizationRepository: ...

    @property
    def approval(self) -> AdminApprovalRepository: ...

    @property
    def audit(self) -> AdminAuditRepository: ...